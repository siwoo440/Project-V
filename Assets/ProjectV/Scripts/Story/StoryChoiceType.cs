// 스토리 선택지의 유형 (기획서 2.10.3)
// 선택지는 대화의 분위기만 바꾼다. 진행, 보상, 해금에는 영향을 주지 않는다.
public enum StoryChoiceType
{
    Serious = 0,  // 진지한 답변: 상대의 상황을 이해하고 현실적으로 대응
    Playful = 1,  // 장난스러운 답변: 도윤의 허세와 농담
    Honest = 2,   // 욕망에 솔직한 답변: 목표와 감정을 그대로 표현
    Grimoire = 3, // 그리모어에게 맡기기: 그리모어가 대신 설명하거나 상황을 악화
}
